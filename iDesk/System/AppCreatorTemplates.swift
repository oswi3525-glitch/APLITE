import Foundation

enum AppTemplate: String, CaseIterable, Identifiable {
    case basic, webView, notes, python, node

    var id: String { rawValue }
    var title: String {
        switch self {
        case .basic: return String(localized: "Hello World")
        case .webView: return String(localized: "Web view")
        case .notes: return String(localized: "Notes")
        case .python: return "Python"
        case .node: return "Node.js"
        }
    }
    var symbol: String {
        switch self {
        case .basic: return "app.fill"
        case .webView: return "globe"
        case .notes: return "note.text"
        case .python: return "chevron.left.forwardslash.chevron.right"
        case .node: return "curlybraces"
        }
    }
    var detail: String {
        switch self {
        case .basic: return String(localized: "A minimal SwiftUI app with a button and a counter.")
        case .webView: return String(localized: "A WKWebView with an address field — a starting point for a site wrapper.")
        case .notes: return String(localized: "A small notes list saved with UserDefaults.")
        case .python: return String(localized: "A Python CLI starter with a requirements file — build needs a worker with Python.")
        case .node: return String(localized: "A Node.js CLI starter with package.json — build needs a worker with Node.")
        }
    }
}

/// Pure text generation for new iOS projects. No Xcode runs on iOS: these are real source files
/// that can be zipped, exported, imported into Build Center and compiled on a macOS worker.
enum AppCreatorTemplates {
    /// A Swift-identifier-safe module name from a user typed display name.
    static func moduleName(_ raw: String) -> String {
        let filtered = raw.unicodeScalars.filter { CharacterSet.alphanumerics.contains($0) || $0 == "_" }
        var name = String(String.UnicodeScalarView(filtered))
        if name.isEmpty { name = "APLiteApp" }
        if name.first?.isNumber == true { name = "App" + name }
        return name
    }

    static func files(template: AppTemplate, displayName: String, bundleID: String) -> [String: String] {
        let module = moduleName(displayName)
        let safeName = displayName.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        let prefix = bundleID.components(separatedBy: ".").dropLast().joined(separator: ".")
        let project = """
        # Generated by APLite App Creator. Build on a macOS worker (xcodegen + xcodebuild).
        name: \(module)
        options:
          bundleIdPrefix: \(prefix.isEmpty ? "com.example" : prefix)
          deploymentTarget:
            iOS: "17.0"
        targets:
          \(module):
            type: application
            platform: iOS
            sources: [Sources]
            settings:
              base:
                PRODUCT_BUNDLE_IDENTIFIER: \(bundleID)
                PRODUCT_NAME: \(displayName)
                SWIFT_VERSION: "5.0"
                TARGETED_DEVICE_FAMILY: "1,2"
                GENERATE_INFOPLIST_FILE: YES
        """
        let app = """
        import SwiftUI

        @main
        struct \(module)App: App {
            var body: some Scene {
                WindowGroup {
                    ContentView()
                }
            }
        }
        """

        let readme = """
        # \(displayName)

        Generated by APLite App Creator on \(Date()).

        Bundle ID: \(bundleID)
        Template: \(template.title)
        """

        // Non-Swift templates: real runnable source plus a build descriptor. APLite never
        // compiles these on iOS — a worker with Python / Node must do it.
        switch template {
        case .python:
            return [
                "main.py": "#!/usr/bin/env python3\n\ndef main():\n    print(\"Hello from \(safeName)!\")\n\n\nif __name__ == \"__main__\":\n    main()\n",
                "requirements.txt": "# Add Python dependencies here, one per line.\n",
                "project.json": """
                {
                  "name": "\(safeName)",
                  "language": "python",
                  "bundleId": "\(bundleID)",
                  "entry": "main.py",
                  "worker": "python"
                }
                """,
                "README.md": readme + "\nBuild on a worker with Python installed: `python3 main.py`.\n",
            ]
        case .node:
            return [
                "index.js": """
                #!/usr/bin/env node
                'use strict';

                function main() {
                  console.log('Hello from \(safeName)!');
                }

                main();
                """,
                "package.json": """
                {
                  "name": "\(module.lowercased())",
                  "version": "1.0.0",
                  "private": true,
                  "main": "index.js",
                  "scripts": { "start": "node index.js" }
                }
                """,
                "project.json": """
                {
                  "name": "\(safeName)",
                  "language": "node",
                  "bundleId": "\(bundleID)",
                  "entry": "index.js",
                  "worker": "node"
                }
                """,
                "README.md": readme + "\nBuild on a worker with Node installed: `npm install && npm start`.\n",
            ]
        default: break
        }

        let content: String
        switch template {
        case .python, .node: content = ""   // handled above, kept for exhaustiveness
        case .basic:
            content = """
            import SwiftUI

            struct ContentView: View {
                @State private var count = 0

                var body: some View {
                    VStack(spacing: 20) {
                        Image(systemName: "app.fill").font(.system(size: 64)).foregroundStyle(.tint)
                        Text("\(safeName)").font(.title.bold())
                        Text("Tapped \\(count) times").foregroundStyle(.secondary)
                        Button("Tap me") { count += 1 }
                            .buttonStyle(.borderedProminent)
                    }
                    .padding()
                }
            }
            """
        case .webView:
            content = """
            import SwiftUI
            import WebKit

            struct ContentView: View {
                @State private var address = "https://example.com"
                @State private var submitted = "https://example.com"

                var body: some View {
                    VStack(spacing: 0) {
                        HStack {
                            TextField("https://", text: $address)
                                .textInputAutocapitalization(.never).keyboardType(.URL)
                                .textFieldStyle(.roundedBorder)
                            Button("Go") {
                                if let url = URL(string: address), url.scheme != nil { submitted = address }
                            }
                        }
                        .padding(8)
                        WebView(url: URL(string: submitted)!)
                    }
                }
            }

            struct WebView: UIViewRepresentable {
                let url: URL
                func makeUIView(context: Context) -> WKWebView {
                    let config = WKWebViewConfiguration()
                    config.allowsInlineMediaPlayback = true
                    config.mediaTypesRequiringUserActionForPlayback = []
                    return WKWebView(frame: .zero, configuration: config)
                }
                func updateUIView(_ web: WKWebView, context: Context) {
                    if web.url != url { web.load(URLRequest(url: url)) }
                }
            }
            """
        case .notes:
            content = """
            import SwiftUI

            struct ContentView: View {
                @AppStorage("notes") private var notes: String = ""
                @State private var draft = ""

                var body: some View {
                    VStack(alignment: .leading) {
                        HStack {
                            TextField("New note", text: $draft)
                                .textFieldStyle(.roundedBorder)
                            Button("Add") {
                                guard !draft.isEmpty else { return }
                                notes = notes.isEmpty ? draft : notes + "\\n" + draft
                                draft = ""
                            }
                        }
                        TextEditor(text: $notes).border(Color.secondary.opacity(0.3))
                    }
                    .padding()
                }
            }
            """
        }

        return [
            "project.yml": project,
            "Sources/\(module)App.swift": app,
            "Sources/ContentView.swift": content,
            "README.md": """
            # \(displayName)

            Generated by APLite App Creator on \(Date()).

            Bundle ID: \(bundleID)
            Template: \(template.title)

            Build it on a macOS worker:
              xcodegen generate && xcodebuild -project \(module).xcodeproj -scheme \(module) \
                -destination 'generic/platform=iOS' CODE_SIGNING_ALLOWED=NO build
            """,
        ]
    }
}
